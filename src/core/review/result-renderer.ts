import type { ReviewResult } from '../schemas/review-result.js'

export function renderReviewMarkdown(params: {
  reviewResult: ReviewResult
  taskId: string
  timestamp: string
  rawOutputPath?: string
}): string {
  const { reviewResult: r, taskId, timestamp, rawOutputPath } = params

  const blockingSection = r.blocking_issues.length > 0
    ? r.blocking_issues.map(b =>
        `- id: ${b.id}\n  severity: ${b.severity}\n  issue: ${b.issue}\n  evidence: ${b.evidence}\n  required_fix: ${b.required_fix}`
      ).join('\n')
    : '(none)'

  const fixesSection = r.required_fixes.length > 0
    ? r.required_fixes.map(f => `- ${f}`).join('\n')
    : '(none)'

  const suggestionsSection = r.non_blocking_suggestions.length > 0
    ? r.non_blocking_suggestions.map(s => `- issue: ${s.issue}\n  rationale: ${s.rationale}`).join('\n')
    : null

  const questionsSection = r.human_questions.length > 0
    ? r.human_questions.map(q =>
        `- question: ${q.question}\n  options:\n${q.options.map(o => `    - ${o}`).join('\n')}`
      ).join('\n')
    : null

  return [
    `# Codex Review`,
    `<!-- Generated by 24h review at ${timestamp} -->`,
    '',
    `## Task ID`,
    '',
    taskId,
    '',
    `## Timestamp`,
    '',
    timestamp,
    '',
    `## Verdict`,
    '',
    r.verdict,
    '',
    `## Confidence`,
    '',
    r.confidence,
    '',
    `## Blocking Issues`,
    '',
    blockingSection,
    '',
    `## Required Fixes`,
    '',
    fixesSection,
    '',
    ...(suggestionsSection ? ['## Non-Blocking Suggestions', '', suggestionsSection, ''] : []),
    ...(questionsSection ? ['## Human Questions', '', questionsSection, ''] : []),
    `## Next Action`,
    '',
    r.next_action,
    '',
    `## Raw Output Path`,
    '',
    rawOutputPath ?? 'not provided',
    ''
  ].join('\n')
}
